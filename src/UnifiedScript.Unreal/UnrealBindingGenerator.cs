using System.Security.Cryptography;
using System.Text;
using System.Text.Json;

namespace UnifiedScript.Unreal;

public sealed record UnrealBindingGeneratorOptions(string Namespace = "UnifiedScript.Unreal.Generated");

public sealed record UnrealBindingDiagnostic(string Code, string Message, string MemberPath);

public sealed record UnrealBindingGenerationResult(
    string Source,
    IReadOnlyList<UnrealBindingDiagnostic> Diagnostics);

public sealed class UnrealBindingGenerator
{
    private static readonly HashSet<string> Keywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char",
        "checked", "class", "const", "continue", "decimal", "default", "delegate", "do",
        "double", "else", "enum", "event", "explicit", "extern", "false", "finally",
        "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int",
        "interface", "internal", "is", "lock", "long", "namespace", "new", "null",
        "object", "operator", "out", "override", "params", "private", "protected", "public",
        "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc",
        "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof",
        "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void",
        "volatile", "while",
    };

    public UnrealBindingGenerationResult Generate(
        UnrealReflectionManifest manifest,
        UnrealBindingGeneratorOptions? options = null)
    {
        UnrealReflectionManifest normalized = UnrealReflectionJson.NormalizeAndValidate(manifest);
        options ??= new UnrealBindingGeneratorOptions();
        if (!IsValidNamespace(options.Namespace))
        {
            throw new ArgumentException(
                $"'{options.Namespace}' is not a valid C# namespace.",
                nameof(options));
        }

        var diagnostics = new List<UnrealBindingDiagnostic>();
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        source.Append("namespace ").Append(options.Namespace).AppendLine(";");
        source.AppendLine();

        var emittedNames = new HashSet<string>(StringComparer.Ordinal);
        foreach (UnrealReflectedType type in normalized.Types)
        {
            if (type.Kind != UnrealReflectedTypeKind.Class)
            {
                diagnostics.Add(new UnrealBindingDiagnostic(
                    "USUE2001",
                    $"Reflected {type.Kind.ToString().ToLowerInvariant()} bindings are deferred.",
                    type.Path));
                continue;
            }

            string className = MakeUniqueTypeName(ToIdentifier(type.Name), type.Path, emittedNames);
            EmitClass(source, type, className, diagnostics);
        }

        return new UnrealBindingGenerationResult(
            source.ToString().TrimEnd().ReplaceLineEndings("\n") + "\n",
            diagnostics
                .OrderBy(static diagnostic => diagnostic.MemberPath, StringComparer.Ordinal)
                .ThenBy(static diagnostic => diagnostic.Code, StringComparer.Ordinal)
                .ToArray());
    }

    private static void EmitClass(
        StringBuilder source,
        UnrealReflectedType type,
        string className,
        ICollection<UnrealBindingDiagnostic> diagnostics)
    {
        source.Append("[global::UnifiedScript.Unreal.UnrealTypeAttribute(")
            .Append(Literal(type.Path)).AppendLine(")]");
        source.Append("public sealed partial class ").Append(className)
            .AppendLine(" : global::UnifiedScript.Unreal.UnrealObject");
        source.AppendLine("{");
        source.Append("    public ").Append(className)
            .AppendLine("(");
        source.AppendLine("        global::UnifiedScript.Unreal.UnrealObjectHandle handle,");
        source.AppendLine("        global::UnifiedScript.Unreal.IUnrealInvocationBridge bridge)");
        source.AppendLine("        : base(handle, bridge)");
        source.AppendLine("    {");
        source.AppendLine("    }");

        var memberNames = new HashSet<string>(StringComparer.Ordinal);
        foreach (UnrealReflectedProperty property in type.Properties)
        {
            string? managedType = GetManagedType(property.Type);
            if (managedType is null)
            {
                diagnostics.Add(new UnrealBindingDiagnostic(
                    "USUE2002",
                    $"Property type '{property.Type.NativeName}' is not supported by binding v0.1.",
                    property.Path));
                continue;
            }

            string memberName = MakeUniqueMemberName(ToIdentifier(property.Name), property.Path, memberNames);
            source.AppendLine();
            source.Append("    public ").Append(managedType).Append(' ').Append(memberName).AppendLine();
            source.AppendLine("    {");
            if (property.Access.Readable)
            {
                source.Append("        get => ReadProperty<").Append(managedType).Append(">(")
                    .Append(Literal(property.Path)).AppendLine(");");
            }

            if (property.Access.Writable)
            {
                source.Append("        set => WriteProperty(").Append(Literal(property.Path))
                    .AppendLine(", value);");
            }

            source.AppendLine("    }");
        }

        foreach (UnrealReflectedFunction function in type.Functions)
        {
            if (function.Traits.Static)
            {
                diagnostics.Add(new UnrealBindingDiagnostic(
                    "USUE2003",
                    "Static UFunction invocation is deferred until the class-default-object bridge exists.",
                    function.Path));
                continue;
            }

            if (function.Parameters.Any(static parameter =>
                    parameter.Direction != UnrealParameterDirection.Input))
            {
                diagnostics.Add(new UnrealBindingDiagnostic(
                    "USUE2004",
                    "Output and input/output UFunction parameters are deferred by binding v0.1.",
                    function.Path));
                continue;
            }

            string? returnType = GetManagedType(function.ReturnType);
            string? unsupportedParameter = function.Parameters
                .FirstOrDefault(parameter => GetManagedType(parameter.Type) is null)
                ?.Name;
            if (returnType is null || unsupportedParameter is not null)
            {
                diagnostics.Add(new UnrealBindingDiagnostic(
                    "USUE2005",
                    unsupportedParameter is null
                        ? $"Return type '{function.ReturnType.NativeName}' is not supported by binding v0.1."
                        : $"Parameter '{unsupportedParameter}' has a type not supported by binding v0.1.",
                    function.Path));
                continue;
            }

            string memberName = MakeUniqueMemberName(ToIdentifier(function.Name), function.Path, memberNames);
            string[] parameterNames = CreateParameterNames(function.Parameters);
            source.AppendLine();
            source.Append("    public ").Append(returnType).Append(' ').Append(memberName).Append('(');
            for (int index = 0; index < function.Parameters.Count; index++)
            {
                if (index > 0)
                {
                    source.Append(", ");
                }

                source.Append(GetManagedType(function.Parameters[index].Type))
                    .Append(' ').Append(parameterNames[index]);
            }

            source.AppendLine(")");
            source.Append("        => ");
            if (function.ReturnType.Kind != UnrealValueKind.Void)
            {
                source.Append("Invoke<").Append(returnType).Append('>');
            }
            else
            {
                source.Append("Invoke");
            }

            source.Append('(').Append(Literal(function.Path));
            foreach (string parameterName in parameterNames)
            {
                source.Append(", ").Append(parameterName);
            }

            source.AppendLine(");");
        }

        source.AppendLine("}");
        source.AppendLine();
    }

    private static string[] CreateParameterNames(
        IReadOnlyList<UnrealReflectedParameter> parameters)
    {
        var used = new HashSet<string>(StringComparer.Ordinal);
        return parameters
            .Select((parameter, index) => MakeUniqueMemberName(
                ToIdentifier(ToCamelCase(parameter.Name)),
                $"{parameter.Name}:{index}",
                used))
            .ToArray();
    }

    private static string? GetManagedType(UnrealTypeReference type) => type.Kind switch
    {
        UnrealValueKind.Void => "void",
        UnrealValueKind.Boolean => "bool",
        UnrealValueKind.Int8 => "sbyte",
        UnrealValueKind.UInt8 => "byte",
        UnrealValueKind.Int16 => "short",
        UnrealValueKind.UInt16 => "ushort",
        UnrealValueKind.Int32 => "int",
        UnrealValueKind.UInt32 => "uint",
        UnrealValueKind.Int64 => "long",
        UnrealValueKind.UInt64 => "ulong",
        UnrealValueKind.Float32 => "float",
        UnrealValueKind.Float64 => "double",
        UnrealValueKind.String or UnrealValueKind.Name or UnrealValueKind.Text => "string",
        UnrealValueKind.Object or UnrealValueKind.Class =>
            "global::UnifiedScript.Unreal.UnrealObjectHandle",
        UnrealValueKind.Array when GetManagedType(type.ElementType!) is string element =>
            $"global::System.Collections.Generic.IReadOnlyList<{element}>",
        UnrealValueKind.Set when GetManagedType(type.ElementType!) is string element =>
            $"global::System.Collections.Generic.IReadOnlySet<{element}>",
        UnrealValueKind.Map
            when GetManagedType(type.KeyType!) is string key &&
                 GetManagedType(type.ValueType!) is string value =>
            $"global::System.Collections.Generic.IReadOnlyDictionary<{key}, {value}>",
        _ => null,
    };

    private static string MakeUniqueTypeName(string candidate, string path, ISet<string> used) =>
        used.Add(candidate) ? candidate : AddStableSuffix(candidate, path, used);

    private static string MakeUniqueMemberName(string candidate, string path, ISet<string> used) =>
        used.Add(candidate) ? candidate : AddStableSuffix(candidate, path, used);

    private static string AddStableSuffix(string candidate, string path, ISet<string> used)
    {
        string suffix = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(path)))[..8];
        string unique = $"{candidate}_{suffix}";
        if (!used.Add(unique))
        {
            throw new InvalidOperationException($"Stable binding-name collision for '{path}'.");
        }

        return unique;
    }

    private static string ToIdentifier(string value)
    {
        var identifier = new StringBuilder(value.Length + 1);
        if (value.Length == 0 || !char.IsLetter(value[0]) && value[0] != '_')
        {
            identifier.Append('_');
        }

        foreach (char character in value)
        {
            identifier.Append(char.IsLetterOrDigit(character) || character == '_' ? character : '_');
        }

        string result = identifier.ToString();
        return Keywords.Contains(result) ? $"@{result}" : result;
    }

    private static string ToCamelCase(string value) =>
        value.Length == 0 || char.IsLower(value[0])
            ? value
            : char.ToLowerInvariant(value[0]) + value[1..];

    private static bool IsValidNamespace(string value) =>
        !string.IsNullOrWhiteSpace(value) &&
        value.Split('.').All(static segment =>
            segment.Length > 0 &&
            (char.IsLetter(segment[0]) || segment[0] == '_') &&
            segment.Skip(1).All(static character => char.IsLetterOrDigit(character) || character == '_') &&
            !Keywords.Contains(segment));

    private static string Literal(string value) => JsonSerializer.Serialize(value);
}
