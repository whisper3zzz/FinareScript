using System.Security.Cryptography;
using System.Text;
using System.Text.Json;

namespace Finare.Unreal;

public sealed record UnrealBindingGeneratorOptions(string Namespace = "Finare.Unreal.Generated");

public sealed record UnrealBindingDiagnostic(string Code, string Message, string MemberPath);

public sealed record UnrealBindingGenerationResult(
    string Source,
    IReadOnlyList<UnrealBindingDiagnostic> Diagnostics);

public sealed class UnrealBindingGenerator
{
    private static readonly HashSet<string> Keywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char",
        "checked", "class", "const", "continue", "decimal", "default", "delegate", "do",
        "double", "else", "enum", "event", "explicit", "extern", "false", "finally",
        "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int",
        "interface", "internal", "is", "lock", "long", "namespace", "new", "null",
        "object", "operator", "out", "override", "params", "private", "protected", "public",
        "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc",
        "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof",
        "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void",
        "volatile", "while",
    };

    public UnrealBindingGenerationResult Generate(
        UnrealReflectionManifest manifest,
        UnrealBindingGeneratorOptions? options = null)
    {
        UnrealReflectionManifest normalized = UnrealReflectionJson.NormalizeAndValidate(manifest);
        options ??= new UnrealBindingGeneratorOptions();
        if (!IsValidNamespace(options.Namespace))
        {
            throw new ArgumentException(
                $"'{options.Namespace}' is not a valid C# namespace.",
                nameof(options));
        }

        var diagnostics = new List<UnrealBindingDiagnostic>();
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        source.Append("namespace ").Append(options.Namespace).AppendLine(";");
        source.AppendLine();

        var managedTypeNames = CreateManagedTypeNames(normalized.Types);
        var reflectedTypes = normalized.Types.ToDictionary(type => type.Path, StringComparer.Ordinal);
        var projectedStructs = new HashSet<string>(StringComparer.Ordinal);
        bool ContainsView(UnrealTypeReference value) =>
            value.Kind is UnrealValueKind.Object or UnrealValueKind.Interface ||
            value.Kind == UnrealValueKind.Struct && value.TypePath is not null && projectedStructs.Contains(value.TypePath) ||
            value.ElementType is not null && ContainsView(value.ElementType) ||
            value.KeyType is not null && ContainsView(value.KeyType) ||
            value.ValueType is not null && ContainsView(value.ValueType);
        while (normalized.Types.Where(t => t.Kind == UnrealReflectedTypeKind.Struct &&
                   t.Properties.Any(p => ContainsView(p.Type))).Count(t => projectedStructs.Add(t.Path)) > 0) { }
        var wireNames = new Dictionary<string, string>(managedTypeNames, StringComparer.Ordinal);
        foreach (string path in projectedStructs)
            wireNames[path] = "__FinareWire_" + Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(path)));

        foreach (var callback in UnrealCallbackBindings.Collect(normalized.Types))
        {
            if (GetManagedType(callback, managedTypeNames) is null) continue;
            var signature = callback.CallbackSignature!;
            source.Append("[global::Finare.Unreal.UnrealCallbackTypeAttribute(").Append(Literal(callback.TypePath!)).AppendLine(")]");
            source.Append("public delegate ").Append(GetManagedType(signature.ReturnType, managedTypeNames)).Append(' ')
                .Append(managedTypeNames[callback.TypePath!]).Append('(');
            EmitParameterList(source, signature.Parameters, CreateParameterNames(signature.Parameters), managedTypeNames);
            source.AppendLine(");");
            source.AppendLine();
        }

        foreach (UnrealReflectedType type in normalized.Types)
        {
            if (type.Kind == UnrealReflectedTypeKind.NativeObject)
            {
                UnrealNativeObjectBindingGenerator.Emit(source, type, managedTypeNames[type.Path], managedTypeNames, diagnostics);
                continue;
            }
            if (type.Kind == UnrealReflectedTypeKind.Struct)
            {
                EmitStruct(source, type, managedTypeNames[type.Path], managedTypeNames, diagnostics,
                    projectedStructs.Contains(type.Path) ? wireNames[type.Path] : null);
                if (projectedStructs.Contains(type.Path))
                    EmitStruct(source, type, wireNames[type.Path], wireNames, diagnostics, wire: true);
                continue;
            }
            if (type.Kind == UnrealReflectedTypeKind.Enum)
            {
                EmitEnum(source, type, managedTypeNames[type.Path]);
                continue;
            }
            if (type.Kind != UnrealReflectedTypeKind.Class)
            {
                diagnostics.Add(new UnrealBindingDiagnostic(
                    "USUE2001",
                    $"Reflected {type.Kind.ToString().ToLowerInvariant()} bindings are deferred.",
                    type.Path));
                continue;
            }

            EmitClass(source, type, managedTypeNames[type.Path], managedTypeNames, reflectedTypes, options.Namespace, diagnostics);
        }

        return new UnrealBindingGenerationResult(
            source.ToString().TrimEnd().ReplaceLineEndings("\n") + "\n",
            diagnostics
                .OrderBy(static diagnostic => diagnostic.MemberPath, StringComparer.Ordinal)
                .ThenBy(static diagnostic => diagnostic.Code, StringComparer.Ordinal)
                .ToArray());
    }

    private static void EmitClass(
        StringBuilder source,
        UnrealReflectedType type,
        string className,
        IReadOnlyDictionary<string, string> managedTypeNames,
        IReadOnlyDictionary<string, UnrealReflectedType> reflectedTypes,
        string namespaceName,
        ICollection<UnrealBindingDiagnostic> diagnostics)
    {
        EmitBlueprintMetadata(source, type.Metadata, string.Empty);
        source.Append("[global::Finare.Unreal.UnrealInheritanceAttribute(")
            .Append(type.BaseTypePath is null ? "null" : Literal(type.BaseTypePath));
        foreach (string interfacePath in type.InterfacePaths)
        {
            source.Append(", ").Append(Literal(interfacePath));
        }
        source.AppendLine(")]");
        source.Append("[global::Finare.Unreal.UnrealTypeAttribute(")
            .Append(Literal(type.Path));
        if (type.Traits.Interface) source.Append(", IsInterface = true");
        source.AppendLine(")]");
        bool staticService = type.Properties.Count == 0 && type.Delegates.Count == 0 &&
            type.Functions.Count > 0 && type.Functions.All(static function => function.Traits.Static);
        string? generatedBaseType = type.BaseTypePath is not null &&
            reflectedTypes.TryGetValue(type.BaseTypePath, out UnrealReflectedType? reflectedBase) &&
            reflectedBase.Kind == UnrealReflectedTypeKind.Class &&
            managedTypeNames.TryGetValue(type.BaseTypePath, out string? baseName)
                ? baseName
                : null;
        source.Append("public partial class ").Append(className)
            .Append(generatedBaseType is not null
                ? " : global::" + namespaceName + "." + generatedBaseType
                : staticService
                    ? " : global::Finare.Unreal.UnrealStaticService"
                    : " : global::Finare.Unreal.UnrealObject")
            .AppendLine();
        source.AppendLine("{");
        source.Append("    public ").Append(className)
            .AppendLine("(");
        source.AppendLine("        global::Finare.Unreal.UnrealObjectHandle handle,");
        source.AppendLine("        global::Finare.Unreal.IUnrealInvocationBridge bridge)");
        source.AppendLine("        : base(handle, bridge)");
        source.AppendLine("    {");
        string[] nativePaths = type.Properties.Where(static field => field.NativeExtension is not null)
            .Select(static field => field.Path)
            .Concat(type.Functions.Where(static method => method.NativeBinding is not null).Select(static method => method.Path))
            .Order(StringComparer.Ordinal).ToArray();
        if (nativePaths.Length > 0)
        {
            source.Append("        RequireNativeBindings(")
                .Append(string.Join(", ", nativePaths.Select(Literal))).AppendLine(");");
        }
        source.AppendLine("    }");

        var memberNames = new HashSet<string>(StringComparer.Ordinal)
            { className, "GetType", "Equals", "GetHashCode", "ToString", "Handle", "Bridge", "Wrap", "As", "IsA" };
        var functionNames = new HashSet<string>(StringComparer.Ordinal);
        foreach (UnrealReflectedProperty property in type.Properties)
        {
            string? managedType = GetManagedType(property.Type, managedTypeNames);
            if (managedType is null)
            {
                diagnostics.Add(new UnrealBindingDiagnostic(
                    "USUE2002",
                    $"Property type '{property.Type.NativeName}' is not supported by binding v0.1.",
                    property.Path));
                continue;
            }

            string memberName = MakeUniqueMemberName(ToIdentifier(property.Name), property.Path, memberNames);
            source.AppendLine();
            EmitBlueprintMetadata(source, property.Metadata, "    ");
            EmitObsolete(source, property.Metadata, "    ");
            source.Append("    public ").Append(managedType).Append(' ').Append(memberName).AppendLine();
            source.AppendLine("    {");
            if (property.Access.Readable)
            {
                source.Append("        get => ReadProperty<").Append(managedType).Append(">(")
                    .Append(MemberIdLiteral(property.Path)).Append(", ")
                    .Append(Literal(property.Path)).AppendLine(");");
            }

            if (property.Access.Writable)
            {
                source.Append("        set => WriteProperty(")
                    .Append(MemberIdLiteral(property.Path)).Append(", ")
                    .Append(Literal(property.Path)).AppendLine(", value);");
            }

            source.AppendLine("    }");
        }

        foreach (UnrealReflectedDelegate reflectedDelegate in type.Delegates)
        {
            if (!reflectedDelegate.Traits.BlueprintAssignable)
            {
                diagnostics.Add(new UnrealBindingDiagnostic(
                    "USUE2006",
                    "The reflected delegate is not BlueprintAssignable and cannot be subscribed through the event bridge.",
                    reflectedDelegate.Path));
                continue;
            }

            string? returnType = GetManagedType(reflectedDelegate.ReturnType, managedTypeNames);
            bool unsupportedReturn = ContainsInterfaceValue(reflectedDelegate.ReturnType);
            string? unsupportedParameter = reflectedDelegate.Parameters
                .FirstOrDefault(parameter => ContainsInterfaceValue(parameter.Type) ||
                    GetManagedType(parameter.Type, managedTypeNames) is null)
                ?.Name;
            string? outputParameter = reflectedDelegate.Parameters
                .FirstOrDefault(parameter =>
                    parameter.Direction != UnrealParameterDirection.Input)
                ?.Name;
            if (returnType is null || unsupportedReturn || unsupportedParameter is not null || outputParameter is not null)
            {
                diagnostics.Add(new UnrealBindingDiagnostic(
                    "USUE2007",
                    outputParameter is not null
                        ? $"Delegate parameter '{outputParameter}' is not input-only; reverse output propagation is not supported by event ABI v4."
                        : unsupportedReturn
                        ? $"Delegate return type '{reflectedDelegate.ReturnType.NativeName}' contains an interface value, which event ABI v4 does not support."
                        : unsupportedParameter is null
                        ? $"Delegate return type '{reflectedDelegate.ReturnType.NativeName}' is not supported by binding v0.2."
                        : $"Delegate parameter '{unsupportedParameter}' has a type not supported by binding v0.2.",
                    reflectedDelegate.Path));
                continue;
            }

            string handlerName = MakeUniqueMemberName(
                ToIdentifier(reflectedDelegate.Name + "Handler"),
                reflectedDelegate.Path + ":handler",
                memberNames);
            string descriptorName = MakeUniqueMemberName(
                ToIdentifier(reflectedDelegate.Name + "Event"),
                reflectedDelegate.Path + ":descriptor",
                memberNames);
            string subscribeName = MakeUniqueMemberName(
                ToIdentifier("Subscribe" + reflectedDelegate.Name),
                reflectedDelegate.Path + ":subscribe",
                memberNames);
            string[] parameterNames = CreateParameterNames(reflectedDelegate.Parameters);

            source.AppendLine();
            source.Append("    public delegate ").Append(returnType).Append(' ')
                .Append(handlerName).Append('(');
            EmitParameterList(source, reflectedDelegate.Parameters, parameterNames, managedTypeNames);
            source.AppendLine(");");

            source.AppendLine();
            source.Append("    public static global::Finare.Unreal.UnrealEventDescriptor ")
                .Append(descriptorName).AppendLine(" { get; } = new(");
            source.Append("        ").Append(MemberIdLiteral(reflectedDelegate.Path)).AppendLine(",");
            source.Append("        ").Append(Literal(reflectedDelegate.Path)).AppendLine(",");
            source.Append("        ").Append(Literal(reflectedDelegate.SignaturePath)).AppendLine(",");
            source.Append("        typeof(").Append(RuntimeTypeName(returnType)).AppendLine("),");
            source.Append("        global::Finare.Unreal.UnrealDelegateKind.")
                .Append(reflectedDelegate.Traits.Kind).AppendLine(",");
            source.AppendLine("        [");
            for (int index = 0; index < reflectedDelegate.Parameters.Count; index++)
            {
                UnrealReflectedParameter parameter = reflectedDelegate.Parameters[index];
                source.Append("            new(").Append(Literal(parameter.Name)).Append(", typeof(")
                    .Append(RuntimeTypeName(GetManagedType(parameter.Type, managedTypeNames))).Append("), ")
                    .Append("global::Finare.Unreal.UnrealParameterDirection.")
                    .Append(parameter.Direction).AppendLine("),");
            }
            source.AppendLine("        ]);");

            source.AppendLine();
            source.Append("    [global::Finare.Unreal.UnrealEventEndpointAttribute(")
                .Append(Literal(reflectedDelegate.Path)).AppendLine(")]");
            source.Append("    public global::Finare.Unreal.IUnrealEventSubscription ").Append(subscribeName)
                .Append('(').Append(handlerName).AppendLine(" handler)");
            source.Append("        => SubscribeEvent(").Append(descriptorName)
                .AppendLine(", handler);");
        }

        foreach (UnrealReflectedFunction function in type.Functions)
        {
            string? returnType = GetManagedType(function.ReturnType, managedTypeNames);
            string? unsupportedParameter = function.Parameters
                .FirstOrDefault(parameter => GetManagedType(parameter.Type, managedTypeNames) is null)
                ?.Name;
            if (returnType is null || unsupportedParameter is not null)
            {
                diagnostics.Add(new UnrealBindingDiagnostic(
                    "USUE2005",
                    unsupportedParameter is null
                        ? $"Return type '{function.ReturnType.NativeName}' is not supported by binding v0.1."
                        : $"Parameter '{unsupportedParameter}' has a type not supported by binding v0.1.",
                    function.Path));
                continue;
            }

            string candidateName = UnrealManagedNaming.FunctionName(function, type);
            string memberName;
            if (!memberNames.Contains(candidateName))
            {
                memberNames.Add(candidateName);
                functionNames.Add(candidateName);
                memberName = candidateName;
            }
            else if (functionNames.Contains(candidateName))
            {
                memberName = candidateName;
            }
            else
            {
                memberName = MakeUniqueMemberName(candidateName, function.Path, memberNames);
                functionNames.Add(memberName);
            }
            string[] parameterNames = CreateParameterNames(function.Parameters);
            foreach (var parameter in function.Parameters.Where(p => p.Type.Kind == UnrealValueKind.Callback))
            {
                string stem = memberName.TrimStart('@');
                if (!stem.EndsWith(parameter.Name, StringComparison.Ordinal)) stem += parameter.Name;
                if (!stem.EndsWith("Callback", StringComparison.Ordinal)) stem += "Callback";
                string factoryName = MakeUniqueMemberName("Create" + stem,
                    function.Path + ":" + parameter.Name + ":callback", memberNames);
                string callbackType = GetManagedType(parameter.Type, managedTypeNames)!;
                source.AppendLine();
                source.Append("    public ").Append(callbackType).Append(' ').Append(factoryName).Append('(')
                    .Append(managedTypeNames[parameter.Type.TypePath!]).AppendLine(" handler)");
                source.Append("        => ").Append(callbackType).AppendLine(".Create(Bridge, handler);");
            }
            source.AppendLine();
            EmitBlueprintMetadata(source, function.Metadata, "    ");
            EmitObsolete(source, function.Metadata, "    ");
            if (function.Traits.Static)
            {
                source.AppendLine("    [global::Finare.Unreal.UnrealStaticFunctionAttribute]");
            }
            source.Append("    public ").Append(returnType).Append(' ').Append(memberName).Append('(');
            EmitParameterList(source, function.Parameters, parameterNames, managedTypeNames);

            source.AppendLine(")");
            if (function.Parameters.Count > 4 || function.ReturnType.Kind == UnrealValueKind.ByteBuffer ||
                function.Parameters.Any(static parameter => parameter.Type.Kind is UnrealValueKind.ByteBuffer or UnrealValueKind.Callback) ||
                function.Parameters.Any(static parameter =>
                    parameter.Direction != UnrealParameterDirection.Input))
            {
                EmitOutputInvocation(
                    source,
                    function,
                    returnType,
                    parameterNames,
                    managedTypeNames);
                EmitDefaultOverloads(
                    source,
                    function,
                    memberName,
                    returnType,
                    parameterNames,
                    managedTypeNames,
                    diagnostics);
                continue;
            }
            source.Append("        => ");
            if (function.ReturnType.Kind != UnrealValueKind.Void)
            {
                source.Append("Invoke<").Append(returnType);
                if (function.Parameters.Count <= 4)
                {
                    foreach (UnrealReflectedParameter parameter in function.Parameters)
                    {
                        source.Append(", ").Append(GetManagedType(parameter.Type, managedTypeNames));
                    }
                }
                source.Append('>');
            }
            else
            {
                source.Append("Invoke");
                if (function.Parameters.Count is > 0 and <= 4)
                {
                    source.Append('<');
                    for (int index = 0; index < function.Parameters.Count; index++)
                    {
                        if (index > 0)
                        {
                            source.Append(", ");
                        }
                        source.Append(GetManagedType(function.Parameters[index].Type, managedTypeNames));
                    }
                    source.Append('>');
                }
            }

            source.Append('(').Append(MemberIdLiteral(function.Path)).Append(", ")
                .Append(Literal(function.Path));
            foreach (string parameterName in parameterNames)
            {
                source.Append(", ").Append(parameterName);
            }

            source.AppendLine(");");
            EmitDefaultOverloads(
                source,
                function,
                memberName,
                returnType,
                parameterNames,
                managedTypeNames,
                diagnostics);
        }

        source.AppendLine("}");
        source.AppendLine();
    }

    private static void EmitStruct(
        StringBuilder source,
        UnrealReflectedType type,
        string structName,
        IReadOnlyDictionary<string, string> managedTypeNames,
        ICollection<UnrealBindingDiagnostic> diagnostics,
        string? wireTypeName = null,
        bool wire = false)
    {
        var fields = new List<(UnrealReflectedProperty Property, string ManagedType, string Name)>();
        var memberNames = new HashSet<string>(StringComparer.Ordinal)
            { structName, "Equals", "GetHashCode", "ToString", "GetType", "Deconstruct" };
        foreach (UnrealReflectedProperty property in type.Properties)
        {
            string? managedType = GetManagedType(property.Type, managedTypeNames, objectViews: !wire);
            if (managedType is null)
            {
                diagnostics.Add(new UnrealBindingDiagnostic(
                    "USUE2002",
                    $"Struct field type '{property.Type.NativeName}' is not supported by binding v0.2.",
                    property.Path));
                continue;
            }
            fields.Add((
                property,
                managedType,
                MakeUniqueMemberName(ToIdentifier(property.Name), property.Path, memberNames)));
        }

        EmitBlueprintMetadata(source, type.Metadata, string.Empty);
        source.Append("[global::Finare.Unreal.UnrealInheritanceAttribute(")
            .Append(type.BaseTypePath is null ? "null" : Literal(type.BaseTypePath));
        foreach (string interfacePath in type.InterfacePaths)
        {
            source.Append(", ").Append(Literal(interfacePath));
        }
        source.AppendLine(")]");
        source.Append("[global::Finare.Unreal.UnrealStructAttribute(")
            .Append(Literal(type.Path)).Append(", ").Append(Literal(type.NativeName)).AppendLine(")]");
        source.AppendLine("[global::Finare.Unreal.UnrealValueAttribute]");
        if (wireTypeName is not null)
            source.Append("[global::Finare.Unreal.UnrealWireTypeAttribute(typeof(").Append(wireTypeName).AppendLine("))]");
        source.Append(wire ? "internal readonly record struct " : "public readonly record struct ").Append(structName).AppendLine("(");
        for (int index = 0; index < fields.Count; index++)
        {
            var field = fields[index];
            source.Append("    [property: global::Finare.Unreal.UnrealStructFieldAttribute(")
                .Append(index).Append(", ").Append(Literal(field.Property.Name)).Append(")] ")
                .Append(field.ManagedType).Append(' ').Append(field.Name)
                .AppendLine(index + 1 == fields.Count ? ");" : ",");
        }
        if (fields.Count == 0)
        {
            source.AppendLine(");");
        }
        source.AppendLine();
    }

    private static void EmitEnum(StringBuilder source, UnrealReflectedType type, string enumName)
    {
        EmitBlueprintMetadata(source, type.Metadata, string.Empty);
        source.Append("[global::Finare.Unreal.UnrealEnumAttribute(")
            .Append(Literal(type.Path)).Append(", ").Append(Literal(type.NativeName)).AppendLine(")]");
        source.AppendLine("[global::Finare.Unreal.UnrealValueAttribute]");
        source.Append("public readonly record struct ").Append(enumName)
            .AppendLine("(long Value) : global::Finare.Unreal.IUnrealEnumValue");
        source.AppendLine("{");
        var names = new HashSet<string>(StringComparer.Ordinal)
            { enumName, "Value", "ToUntyped", "Equals", "GetHashCode", "ToString", "GetType", "Deconstruct" };
        foreach (UnrealEnumValueDefinition value in type.EnumValues)
        {
            string name = MakeUniqueMemberName(ToIdentifier(value.Name), $"{type.Path}:{value.Name}", names);
            source.Append("    [global::Finare.Unreal.UnrealEnumConstantAttribute(")
                .Append(value.Value).AppendLine(")]")
                .Append("    public static ").Append(enumName).Append(' ')
                .Append(name).Append(" { get; } = new(")
                .Append(value.Value).AppendLine(");");
        }
        source.AppendLine();
        source.Append("    public global::Finare.Unreal.UnrealEnumValue ToUntyped() => new(")
            .Append(Literal(type.Path)).AppendLine(", Value);");
        source.AppendLine("}");
        source.AppendLine();
    }

    private static void EmitParameterList(
        StringBuilder source,
        IReadOnlyList<UnrealReflectedParameter> parameters,
        IReadOnlyList<string> parameterNames,
        IReadOnlyDictionary<string, string> managedTypeNames)
    {
        for (int index = 0; index < parameters.Count; index++)
        {
            if (index > 0)
            {
                source.Append(", ");
            }

            source.Append(DirectionModifier(parameters[index].Direction))
                .Append(GetManagedType(parameters[index].Type, managedTypeNames))
                .Append(' ').Append(parameterNames[index]);
        }
    }

    private static void EmitOutputInvocation(
        StringBuilder source,
        UnrealReflectedFunction function,
        string returnType,
        IReadOnlyList<string> parameterNames,
        IReadOnlyDictionary<string, string> managedTypeNames)
    {
        string resultName = "__unifiedScriptResult";
        while (parameterNames.Contains(resultName, StringComparer.Ordinal))
        {
            resultName += "_";
        }
        source.AppendLine("    {");
        source.Append("        global::Finare.Unreal.UnrealOutputInvocationResult ")
            .Append(resultName).AppendLine(" = InvokeWithOutputs(");
        source.Append("            ").Append(MemberIdLiteral(function.Path)).AppendLine(",");
        source.Append("            ").Append(Literal(function.Path)).AppendLine(",");
        source.Append("            typeof(").Append(RuntimeTypeName(returnType)).AppendLine("),");
        source.AppendLine("            [");
        for (int index = 0; index < function.Parameters.Count; index++)
        {
            UnrealReflectedParameter parameter = function.Parameters[index];
            bool callback = parameter.Type.Kind == UnrealValueKind.Callback;
            string managedType = callback ? "global::Finare.Unreal.UnrealCallbackArgument" : GetManagedType(parameter.Type, managedTypeNames)!;
            source.Append("                new(typeof(").Append(RuntimeTypeName(managedType)).Append("), ")
                .Append("global::Finare.Unreal.UnrealParameterDirection.")
                .Append(parameter.Direction).Append(", ")
                .Append(parameter.Direction == UnrealParameterDirection.Output
                    ? "null"
                    : callback ? parameterNames[index] + ".AsArgument(Bridge)" : parameterNames[index])
                .AppendLine("),");
        }
        source.AppendLine("            ]);");

        int outputIndex = 0;
        for (int index = 0; index < function.Parameters.Count; index++)
        {
            UnrealReflectedParameter parameter = function.Parameters[index];
            if (parameter.Direction == UnrealParameterDirection.Input)
            {
                continue;
            }
            source.Append("        ").Append(parameterNames[index]).Append(" = (")
                .Append(GetManagedType(parameter.Type, managedTypeNames)).Append(')')
                .Append(resultName).Append(".Outputs[").Append(outputIndex++)
                .AppendLine("]!;");
        }
        if (function.ReturnType.Kind != UnrealValueKind.Void)
        {
            source.Append("        return (").Append(returnType).Append(')')
                .Append(resultName).AppendLine(".ReturnValue!;");
        }
        source.AppendLine("    }");
    }

    private static void EmitDefaultOverloads(
        StringBuilder source,
        UnrealReflectedFunction function,
        string memberName,
        string returnType,
        IReadOnlyList<string> parameterNames,
        IReadOnlyDictionary<string, string> managedTypeNames,
        ICollection<UnrealBindingDiagnostic> diagnostics)
    {
        int firstDefault = function.Parameters.Count;
        while (firstDefault > 0 &&
               function.Parameters[firstDefault - 1].Direction == UnrealParameterDirection.Input &&
               function.Parameters[firstDefault - 1].DefaultValue is not null)
        {
            --firstDefault;
        }
        if (firstDefault == function.Parameters.Count)
        {
            return;
        }
        (int FirstDefault, string?[] Expressions)? projectedDefaults =
            GetProjectableDefaultExpressions(function, managedTypeNames);
        if (projectedDefaults is null)
        {
            diagnostics.Add(new UnrealBindingDiagnostic(
                "USUE2008",
                "One or more reflected default parameter literals cannot be projected safely to C#; callers must pass those parameters explicitly.",
                function.Path));
            return;
        }
        int firstProjectedDefault = projectedDefaults.Value.FirstDefault;
        string?[] defaults = projectedDefaults.Value.Expressions;

        for (int count = function.Parameters.Count - 1; count >= firstProjectedDefault; --count)
        {
            source.AppendLine();
            EmitObsolete(source, function.Metadata, "    ");
            source.Append("    public ").Append(returnType).Append(' ').Append(memberName).Append('(');
            EmitParameterList(
                source,
                function.Parameters.Take(count).ToArray(),
                parameterNames.Take(count).ToArray(),
                managedTypeNames);
            source.AppendLine(")");
            source.Append("        => ");
            if (function.ReturnType.Kind == UnrealValueKind.Void)
            {
                source.Append(memberName).Append('(');
            }
            else
            {
                source.Append(memberName).Append('(');
            }
            for (int index = 0; index < function.Parameters.Count; index++)
            {
                if (index > 0)
                {
                    source.Append(", ");
                }
                if (index < count) source.Append(DirectionModifier(function.Parameters[index].Direction));
                source.Append(index < count ? parameterNames[index] : defaults[index]);
            }
            source.AppendLine(");");
        }
    }

    internal static (int FirstDefault, string?[] Expressions)? GetProjectableDefaultExpressions(
        UnrealReflectedFunction function,
        IReadOnlyDictionary<string, string> managedTypeNames)
    {
        ArgumentNullException.ThrowIfNull(function);
        ArgumentNullException.ThrowIfNull(managedTypeNames);
        int firstDefault = function.Parameters.Count;
        while (firstDefault > 0 &&
               function.Parameters[firstDefault - 1].Direction == UnrealParameterDirection.Input &&
               function.Parameters[firstDefault - 1].DefaultValue is not null)
        {
            --firstDefault;
        }
        if (firstDefault == function.Parameters.Count)
        {
            return null;
        }

        string?[] expressions = function.Parameters
            .Select(parameter => GetDefaultExpression(parameter, managedTypeNames))
            .ToArray();
        return expressions.Skip(firstDefault).Any(static value => value is null)
            ? null
            : (firstDefault, expressions);
    }

    private static string? GetDefaultExpression(
        UnrealReflectedParameter parameter,
        IReadOnlyDictionary<string, string> managedTypeNames)
    {
        string? value = parameter.DefaultValue;
        if (value is null)
        {
            return null;
        }
        return parameter.Type.Kind switch
        {
            UnrealValueKind.Boolean when bool.TryParse(value, out bool boolean) =>
                boolean ? "true" : "false",
            UnrealValueKind.Int8 or UnrealValueKind.UInt8 or
                UnrealValueKind.Int16 or UnrealValueKind.UInt16 or
                UnrealValueKind.Int32 or UnrealValueKind.UInt32 or
                UnrealValueKind.Int64 or UnrealValueKind.UInt64
                when long.TryParse(value, System.Globalization.NumberStyles.Integer,
                    System.Globalization.CultureInfo.InvariantCulture, out _) => value,
            UnrealValueKind.Float32 when float.TryParse(value,
                System.Globalization.NumberStyles.Float,
                System.Globalization.CultureInfo.InvariantCulture, out _) => value + "f",
            UnrealValueKind.Float64 when double.TryParse(value,
                System.Globalization.NumberStyles.Float,
                System.Globalization.CultureInfo.InvariantCulture, out _) => value + "d",
            UnrealValueKind.String => Literal(value),
            UnrealValueKind.Name => $"new global::Finare.Unreal.UnrealName({Literal(value)})",
            UnrealValueKind.Text => $"new global::Finare.Unreal.UnrealText({Literal(value)})",
            UnrealValueKind.SoftObject =>
                $"new global::Finare.Unreal.UnrealSoftObjectHandle({Literal(value)})",
            UnrealValueKind.SoftClass =>
                $"new global::Finare.Unreal.UnrealSoftClassHandle({Literal(value)})",
            UnrealValueKind.Object or UnrealValueKind.Class or UnrealValueKind.Interface when value is "None" or "null" => "default",
            UnrealValueKind.Enum when parameter.Type.TypePath is not null &&
                managedTypeNames.TryGetValue(parameter.Type.TypePath, out string? enumName) &&
                long.TryParse(value,
                System.Globalization.NumberStyles.Integer,
                System.Globalization.CultureInfo.InvariantCulture, out _) =>
                $"new {enumName}({value})",
            UnrealValueKind.Enum when long.TryParse(value,
                System.Globalization.NumberStyles.Integer,
                System.Globalization.CultureInfo.InvariantCulture, out _) =>
                $"new global::Finare.Unreal.UnrealEnumValue({Literal(parameter.Type.TypePath!)}, {value})",
            _ => null,
        };
    }

    private static void EmitBlueprintMetadata(
        StringBuilder source,
        UnrealBlueprintMetadata metadata,
        string indentation)
    {
        if (metadata.DisplayName is null && metadata.Category is null && metadata.Tooltip is null &&
            metadata.WorldContextParameter is null && !metadata.Latent &&
            metadata.LatentInfoParameter is null && !metadata.ThreadSafe &&
            !metadata.CallableWithoutWorldContext)
        {
            return;
        }
        source.Append(indentation).Append("[global::Finare.Unreal.UnrealBlueprintMetadataAttribute(");
        bool hasPrevious = false;
        if (metadata.DisplayName is not null)
        {
            source.Append("DisplayName = ").Append(Literal(metadata.DisplayName));
            hasPrevious = true;
        }
        if (metadata.Category is not null)
        {
            if (hasPrevious) source.Append(", ");
            source.Append("Category = ").Append(Literal(metadata.Category));
            hasPrevious = true;
        }
        if (metadata.Tooltip is not null)
        {
            if (hasPrevious) source.Append(", ");
            source.Append("Tooltip = ").Append(Literal(metadata.Tooltip));
            hasPrevious = true;
        }
        if (metadata.WorldContextParameter is not null)
        {
            if (hasPrevious) source.Append(", ");
            source.Append("WorldContextParameter = ").Append(Literal(metadata.WorldContextParameter));
            hasPrevious = true;
        }
        if (metadata.Latent)
        {
            if (hasPrevious) source.Append(", ");
            source.Append("Latent = true");
            hasPrevious = true;
        }
        if (metadata.LatentInfoParameter is not null)
        {
            if (hasPrevious) source.Append(", ");
            source.Append("LatentInfoParameter = ").Append(Literal(metadata.LatentInfoParameter));
            hasPrevious = true;
        }
        if (metadata.ThreadSafe)
        {
            if (hasPrevious) source.Append(", ");
            source.Append("ThreadSafe = true");
            hasPrevious = true;
        }
        if (metadata.CallableWithoutWorldContext)
        {
            if (hasPrevious) source.Append(", ");
            source.Append("CallableWithoutWorldContext = true");
        }
        source.AppendLine(")]");
    }

    private static void EmitObsolete(
        StringBuilder source,
        UnrealBlueprintMetadata metadata,
        string indentation)
    {
        if (!metadata.Deprecated)
        {
            return;
        }
        source.Append(indentation).Append("[global::System.Obsolete(")
            .Append(Literal(metadata.DeprecationMessage ?? "Deprecated Unreal API."))
            .AppendLine(")]");
    }

    private static string DirectionModifier(UnrealParameterDirection direction) => direction switch
    {
        UnrealParameterDirection.Input => string.Empty,
        UnrealParameterDirection.Output => "out ",
        UnrealParameterDirection.InputOutput => "ref ",
        _ => throw new ArgumentOutOfRangeException(nameof(direction)),
    };

    private static string[] CreateParameterNames(
        IReadOnlyList<UnrealReflectedParameter> parameters)
    {
        var used = new HashSet<string>(StringComparer.Ordinal);
        return parameters
            .Select((parameter, index) => MakeUniqueMemberName(
                ToIdentifier(ToCamelCase(parameter.Name)),
                $"{parameter.Name}:{index}",
                used))
            .ToArray();
    }

    internal static string? GetManagedType(
        UnrealTypeReference type,
        IReadOnlyDictionary<string, string> managedTypeNames,
        bool objectViews = true) => type.Kind switch
        {
            UnrealValueKind.Void => "void",
            UnrealValueKind.Boolean => "bool",
            UnrealValueKind.Int8 => "sbyte",
            UnrealValueKind.UInt8 => "byte",
            UnrealValueKind.Int16 => "short",
            UnrealValueKind.UInt16 => "ushort",
            UnrealValueKind.Int32 => "int",
            UnrealValueKind.UInt32 => "uint",
            UnrealValueKind.Int64 => "long",
            UnrealValueKind.UInt64 => "ulong",
            UnrealValueKind.Float32 => "float",
            UnrealValueKind.Float64 => "double",
            UnrealValueKind.String => "string",
            UnrealValueKind.Name => "global::Finare.Unreal.UnrealName",
            UnrealValueKind.Text => "global::Finare.Unreal.UnrealText",
            UnrealValueKind.ByteBuffer => "global::Finare.Unreal.UnrealByteBuffer",
            UnrealValueKind.Callback when type.TypePath is not null && managedTypeNames.TryGetValue(type.TypePath, out string? callbackName) &&
                type.CallbackSignature is { } signature &&
                !ContainsInterfaceValue(signature.ReturnType) &&
                signature.Parameters.All(parameter => !ContainsInterfaceValue(parameter.Type)) &&
                signature.Parameters.Select(p => p.Type).Append(signature.ReturnType).All(t =>
                    t.Kind is not (UnrealValueKind.NativeObject or UnrealValueKind.InvocationContext) && GetManagedType(t, managedTypeNames) is not null) =>
                $"global::Finare.Unreal.UnrealCallback<{callbackName}>",
            UnrealValueKind.Object or UnrealValueKind.Interface when !objectViews => "global::Finare.Unreal.UnrealObjectHandle",
            UnrealValueKind.Object =>
                type.TypePath is not null && managedTypeNames.TryGetValue(type.TypePath, out string? objectName)
                    ? objectName + "?"
                    : "global::Finare.Unreal.UnrealObject?",
            UnrealValueKind.Interface =>
                type.TypePath is not null && managedTypeNames.TryGetValue(type.TypePath, out string? interfaceName)
                    ? interfaceName + "?"
                    : "global::Finare.Unreal.UnrealObject?",
            UnrealValueKind.NativeObject when type.TypePath is not null && managedTypeNames.TryGetValue(type.TypePath, out string? nativeName) => nativeName,
            UnrealValueKind.Class =>
                "global::Finare.Unreal.UnrealClassHandle",
            UnrealValueKind.SoftObject =>
                "global::Finare.Unreal.UnrealSoftObjectHandle",
            UnrealValueKind.SoftClass =>
                "global::Finare.Unreal.UnrealSoftClassHandle",
            UnrealValueKind.Enum when type.TypePath is not null &&
                managedTypeNames.TryGetValue(type.TypePath, out string? enumName) => enumName,
            UnrealValueKind.Enum => "global::Finare.Unreal.UnrealEnumValue",
            UnrealValueKind.Struct when type.TypePath == "/Script/CoreUObject.Vector" =>
                "global::Finare.Unreal.UnrealVector",
            UnrealValueKind.Struct when type.TypePath == "/Script/CoreUObject.Rotator" =>
                "global::Finare.Unreal.UnrealRotator",
            UnrealValueKind.Struct when type.TypePath == "/Script/CoreUObject.Transform" =>
                "global::Finare.Unreal.UnrealTransform",
            UnrealValueKind.Struct when type.TypePath is not null &&
                managedTypeNames.TryGetValue(type.TypePath, out string? structName) => structName,
            UnrealValueKind.Array when !ContainsInterfaceValue(type) && GetManagedType(type.ElementType!, managedTypeNames, objectViews) is string element =>
                $"global::System.Collections.Generic.IReadOnlyList<{element}>",
            UnrealValueKind.Set when !ContainsInterfaceValue(type) && GetManagedType(type.ElementType!, managedTypeNames, objectViews) is string element =>
                $"global::System.Collections.Generic.IReadOnlySet<{element}>",
            UnrealValueKind.Map
                when !ContainsInterfaceValue(type) &&
                     GetManagedType(type.KeyType!, managedTypeNames, objectViews) is string key &&
                     GetManagedType(type.ValueType!, managedTypeNames, objectViews) is string value =>
                $"global::System.Collections.Generic.IReadOnlyDictionary<{key}, {value}>",
            _ => null,
        };

    public static IReadOnlyDictionary<string, string> CreateManagedTypeNames(IReadOnlyList<UnrealReflectedType> types)
    {
        var names = new Dictionary<string, string>(StringComparer.Ordinal);
        var used = new HashSet<string>(StringComparer.Ordinal);
        foreach (var type in types)
        {
            string candidate = type.Kind == UnrealReflectedTypeKind.Struct
                ? ToIdentifier(TrimNativeStructPrefix(type.NativeName)) : ToIdentifier(type.Name);
            names.Add(type.Path, MakeUniqueTypeName(candidate, type.Path, used));
        }
        foreach (var callback in UnrealCallbackBindings.Collect(types))
            names.Add(callback.TypePath!, MakeUniqueTypeName(ToIdentifier(TrimNativeStructPrefix(callback.NativeName)) + "Handler", callback.TypePath!, used));
        return names;
    }

    private static string RuntimeTypeName(string? managedType) =>
        (managedType ?? throw new InvalidOperationException("A reflected managed type is required."))
        .Replace("?", string.Empty, StringComparison.Ordinal);

    private static string TrimNativeStructPrefix(string nativeName) =>
        nativeName.Length > 1 && nativeName[0] == 'F' ? nativeName[1..] : nativeName;

    private static bool ContainsInterfaceValue(UnrealTypeReference type) =>
        type.Kind == UnrealValueKind.Interface ||
        type.ElementType is not null && ContainsInterfaceValue(type.ElementType) ||
        type.KeyType is not null && ContainsInterfaceValue(type.KeyType) ||
        type.ValueType is not null && ContainsInterfaceValue(type.ValueType) ||
        type.CallbackSignature is { } signature &&
            (ContainsInterfaceValue(signature.ReturnType) ||
             signature.Parameters.Any(parameter => ContainsInterfaceValue(parameter.Type)));

    private static string MakeUniqueTypeName(string candidate, string path, ISet<string> used) =>
        used.Add(candidate) ? candidate : AddStableSuffix(candidate, path, used);

    private static string MakeUniqueMemberName(string candidate, string path, ISet<string> used) =>
        used.Add(candidate) ? candidate : AddStableSuffix(candidate, path, used);

    private static string AddStableSuffix(string candidate, string path, ISet<string> used)
    {
        string suffix = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(path)))[..8];
        string unique = $"{candidate}_{suffix}";
        if (!used.Add(unique))
        {
            throw new InvalidOperationException($"Stable binding-name collision for '{path}'.");
        }

        return unique;
    }

    private static string ToIdentifier(string value)
    {
        var identifier = new StringBuilder(value.Length + 1);
        if (value.Length == 0 || !char.IsLetter(value[0]) && value[0] != '_')
        {
            identifier.Append('_');
        }

        foreach (char character in value)
        {
            identifier.Append(char.IsLetterOrDigit(character) || character == '_' ? character : '_');
        }

        string result = identifier.ToString();
        return Keywords.Contains(result) ? $"@{result}" : result;
    }

    private static string ToCamelCase(string value) =>
        value.Length == 0 || char.IsLower(value[0])
            ? value
            : char.ToLowerInvariant(value[0]) + value[1..];

    private static bool IsValidNamespace(string value) =>
        !string.IsNullOrWhiteSpace(value) &&
        value.Split('.').All(static segment =>
            segment.Length > 0 &&
            (char.IsLetter(segment[0]) || segment[0] == '_') &&
            segment.Skip(1).All(static character => char.IsLetterOrDigit(character) || character == '_') &&
            !Keywords.Contains(segment));

    private static string Literal(string value) => JsonSerializer.Serialize(value);

    private static string MemberIdLiteral(string memberPath) =>
        $"0x{UnrealMemberId.FromPath(memberPath):X16}UL";
