UEdGraph* FindInterfaceGraph(UBlueprint* Blueprint)
{
    for (const FBPInterfaceDescription& Interface : Blueprint->ImplementedInterfaces)
    {
        for (UEdGraph* Graph : Interface.Graphs)
        {
            if (Graph != nullptr && Graph->GetFName() == TEXT("TransformManagedValue"))
            {
                return Graph;
            }
        }
    }
    return nullptr;
}

bool SetInterfaceReturnValue(UBlueprint* Blueprint, int32 Value)
{
    UEdGraph* Graph = FindInterfaceGraph(Blueprint);
    if (Graph == nullptr)
    {
        return false;
    }

    TArray<UK2Node_FunctionResult*> ResultNodes;
    Graph->GetNodesOfClass(ResultNodes);
    TArray<UK2Node_FunctionEntry*> EntryNodes;
    Graph->GetNodesOfClass(EntryNodes);
    const UEdGraphSchema_K2* Schema = GetDefault<UEdGraphSchema_K2>();
    for (UK2Node_FunctionResult* Result : ResultNodes)
    {
        if (Result == nullptr)
        {
            continue;
        }
        if (UEdGraphPin* ReturnPin = Result->FindPin(TEXT("ReturnValue"), EGPD_Input))
        {
            // Keep the function result connected to a real Blueprint literal so
            // this test receives a deterministic value from the Blueprint VM.
            UK2Node_CallFunction* Literal = NewObject<UK2Node_CallFunction>(Graph);
            Literal->FunctionReference.SetExternalMember(
                GET_FUNCTION_NAME_CHECKED(UKismetSystemLibrary, MakeLiteralInt),
                UKismetSystemLibrary::StaticClass());
            Graph->AddNode(Literal, true, false);
            Literal->AllocateDefaultPins();
            UEdGraphPin* LiteralInput = Literal->FindPin(TEXT("Value"), EGPD_Input);
            UEdGraphPin* LiteralOutput = Literal->GetReturnValuePin();
            if (LiteralInput == nullptr || LiteralOutput == nullptr)
            {
                return false;
            }
            Schema->TrySetDefaultValue(*LiteralInput, LexToString(Value));
            UE_LOG(
                LogTemp,
                Display,
                TEXT("Interface test graph return: value='%s' ignored=%d autogenerated='%s' links=%d"),
                *LiteralInput->DefaultValue,
                LiteralInput->bDefaultValueIsIgnored ? 1 : 0,
                *ReturnPin->AutogeneratedDefaultValue,
                ReturnPin->LinkedTo.Num());
            UEdGraphPin* EntryThen = EntryNodes.Num() == 1
                ? EntryNodes[0]->FindPin(UEdGraphSchema_K2::PN_Then, EGPD_Output)
                : nullptr;
            return EntryThen != nullptr &&
                Result->GetExecPin() != nullptr &&
                Schema->TryCreateConnection(EntryThen, Result->GetExecPin()) &&
                Schema->TryCreateConnection(LiteralOutput, ReturnPin);
        }
    }
    return false;
}
